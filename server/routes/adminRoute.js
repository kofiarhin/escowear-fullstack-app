const { Router } = require("express");
const Order = require("../Models/Order.model");
const OrderEvent = require("../Models/OrderEvent.model");
const EmailOutbox = require("../Models/EmailOutbox.model");
const User = require("../Models/User.model");
const PaymentProof = require("../Models/PaymentProof.model");
const HeroSlide = require("../Models/HeroSlide.model");
const FeaturedSneakers = require("../Models/FeaturedSneakers.model");
const HomepageClassics = require("../Models/HomepageClassics.model");
const HomepageLatestReleases = require("../Models/HomepageLatestReleases.model");
const Product = require("../Models/Product.model");
const ProductImageUpload = require("../Models/ProductImageUpload.model");
const { createAuth } = require("../middlewares/auth.middleware");
const { createRateLimiter } = require("../middlewares/rateLimit");
const { createOrderWorkflow } = require("../services/orderWorkflow");
const { createPaymentProofService } = require("../services/paymentProofService");
const { createProofStorage } = require("../services/proofStorage");
const { createAdminOrdersController } = require("../controllers/adminOrdersController");
const { getOrderConfig } = require("../config/orders");
const { createHeroSlidesController } = require("../controllers/heroSlidesController");
const { createFeaturedSneakersController } = require("../controllers/featuredSneakersController");
const { createClassicsController } = require("../controllers/classicsController");
const { createLatestReleasesController } = require("../controllers/latestReleasesController");
const { createAdminProductsController } = require("../controllers/adminProductsController");
const { createAdminStatsController } = require("../controllers/adminStatsController");
const { createAdminUsersController } = require("../controllers/adminUsersController");
const { createEmailVerificationService } = require("../services/emailVerificationService");
const { createProductImageStorage } = require("../services/productImageStorage");

// Every route here requires a logged-in user whose stored role is "admin".
const createAdminRouter = (deps = {}) => {
  const models = { Order, OrderEvent, EmailOutbox, User, PaymentProof, HeroSlide, FeaturedSneakers, HomepageClassics, HomepageLatestReleases, Product, ProductImageUpload, ...deps.models };
  const config = deps.config || getOrderConfig();
  const { auth, requireAdmin } = createAuth(models.User);
  const storage = deps.proofStorage || createProofStorage({ rootDir: config.proofUploadDir });
  const proofs =
    deps.proofs || createPaymentProofService({ ...models, storage, config, env: deps.env, now: deps.now, logger: deps.logger });
  const workflow = deps.workflow || createOrderWorkflow({ ...models, config, env: deps.env, now: deps.now, logger: deps.logger, proofs });
  const controller = createAdminOrdersController({ ...models, workflow, proofs, logger: deps.logger });
  const heroSlides = createHeroSlidesController({ HeroSlide: models.HeroSlide, Product: models.Product });
  const featured = createFeaturedSneakersController({ FeaturedSneakers: models.FeaturedSneakers, Product: models.Product });
  const classics = createClassicsController({ HomepageClassics: models.HomepageClassics, Product: models.Product });
  const latestReleases = createLatestReleasesController({ HomepageLatestReleases: models.HomepageLatestReleases, Product: models.Product });
  const products = createAdminProductsController({ Product: models.Product, ProductImageUpload: models.ProductImageUpload, imageStorage: deps.imageStorage || createProductImageStorage({ env: deps.env }), logger: deps.logger });
  const stats = createAdminStatsController({ Order: models.Order, Product: models.Product, HeroSlide: models.HeroSlide, FeaturedSneakers: models.FeaturedSneakers, logger: deps.logger });
  const verificationService =
    deps.verificationService ||
    createEmailVerificationService({ User: models.User, EmailOutbox: models.EmailOutbox, publicBaseUrl: deps.publicBaseUrl, now: deps.now, logger: deps.logger });
  const users = createAdminUsersController({ User: models.User, EmailOutbox: models.EmailOutbox, verificationService, logger: deps.logger });
  const limiter = createRateLimiter({ windowMs: 60 * 1000, max: 120, keyFn: (req) => String(req.user?._id || req.ip) });
  const uploadLimiter = createRateLimiter({ windowMs: 60 * 1000, max: 20, keyFn: (req) => String(req.user?._id || req.ip), message: "Too many image uploads, please try again later" });

  const router = Router();
  router.use(auth, requireAdmin, limiter);
  router.get("/stats", stats.getStats);
  router.get("/orders", controller.listOrders);
  router.get("/users", users.listUsers);
  router.patch("/users/:id/block", users.setBlocked);
  router.delete("/users/:id", users.deleteUser);
  router.post("/users/:id/resend-verification", users.resendVerification);
  router.get("/hero-slides", heroSlides.listAdminSlides);
  router.post("/hero-slides", heroSlides.createSlide);
  router.patch("/hero-slides/:id", heroSlides.updateSlide);
  router.delete("/hero-slides/:id", heroSlides.deleteSlide);
  router.get("/featured-sneakers", featured.getAdminFeatured);
  router.put("/featured-sneakers", featured.saveFeatured);
  router.get("/classics", classics.getAdminClassics);
  router.put("/classics", classics.saveClassics);
  router.get("/latest-releases", latestReleases.getAdminLatestReleases);
  router.put("/latest-releases", latestReleases.saveLatestReleases);
  router.get("/products", products.listProducts);
  router.get("/products/brands", products.listBrands);
  router.get("/products/:id", products.getProduct);
  router.post("/products", products.createProduct);
  router.patch("/products/:id", products.updateProduct);
  router.patch("/products/:id/publish", products.publishProduct);
  router.patch("/products/:id/unpublish", products.unpublishProduct);
  router.post("/products/images", uploadLimiter, products.uploadImage);
  router.get("/orders/:id", controller.getOrder);
  router.post("/orders/:id/payment-instructions", controller.paymentInstructions);
  router.post("/orders/:id/awaiting-customer", controller.awaitingCustomer);
  router.post("/orders/:id/payment-review", controller.paymentReview);
  router.post("/orders/:id/verify-payment", controller.verifyPayment);
  router.post("/orders/:id/payment-issue", controller.paymentIssue);
  router.post("/orders/:id/fulfilment", controller.fulfilment);
  router.post("/orders/:id/cancel", controller.cancel);
  router.post("/orders/:id/refund", controller.refund);
  router.post("/orders/:id/customer-update", controller.customerUpdate);
  router.get("/orders/:id/payment-proof/:proofId", controller.paymentProofImage);
  router.post("/orders/:id/notes", controller.addNote);
  router.post("/orders/:id/events/:eventId/requeue-email", controller.requeueEventEmail);
  router.post("/emails/:emailId/retry", controller.retryEmail);
  return router;
};

module.exports = { createAdminRouter };
